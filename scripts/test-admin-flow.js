'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const admin=fs.readFileSync('public/admin.html','utf8');
const ops=fs.readFileSync('public/operacional.html','utf8');
const api=fs.readFileSync('api/access.js','utf8');
const script=admin.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert(script,'Script da gestão de usuários ausente');
new vm.Script(script,{filename:'public/admin.html'});
assert(admin.includes('id="userForm"'),'Formulário de cadastro ausente');
assert(admin.includes("api('users',b.id?'PATCH':'POST',b)"),'Cadastro/edição sem chamada à API');
assert(admin.includes("await api('login','POST'"),'Login administrativo ausente');
assert(admin.includes("await refresh()"),'Usuários não são carregados após login');
assert(!admin.includes("window.location.assign('/operacional.html')"),'Login administrativo redireciona indevidamente');
assert(admin.includes("['Master','Gerente'].includes(d.user?.perfil)"),'Permissão administrativa não validada na interface');
assert(ops.includes('href="/admin.html"'),'Link para gestão de usuários ausente');
assert(api.includes("if(!['Master','Gerente'].includes(actor.perfil))"),'API sem proteção de perfil');
assert(api.includes("method==='POST'&&action==='users'"),'API de cadastro ausente');
assert(api.includes("method==='PATCH'&&action==='users'"),'API de edição ausente');
console.log('OK: fluxo de login, navegação, permissão e cadastro de usuários (verificações estáticas)');
